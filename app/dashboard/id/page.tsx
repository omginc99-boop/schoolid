import { requireSession } from '@/lib/auth';
import { roleMeta } from '@/lib/roles';
import IdCard from '@/components/identity/IdCard';
import VerifyIdentity from '@/components/identity/VerifyIdentity';
import { PanelCard } from '@/components/ui/primitives';
import { Fingerprint, QrCode, ArrowRightLeft, Lock } from 'lucide-react';

const COUNTRY_CODES: Record<string, string> = {
  nigeria: 'NG', 'south africa': 'ZA', ghana: 'GH', kenya: 'KE', egypt: 'EG',
  ethiopia: 'ET', tanzania: 'TZ', uganda: 'UG', rwanda: 'RW', senegal: 'SN',
  cameroon: 'CM', zambia: 'ZM', zimbabwe: 'ZW', botswana: 'BW', namibia: 'NA',
  morocco: 'MA', algeria: 'DZ', tunisia: 'TN',
};

export const metadata = { title: 'My SchoolID' };

export default async function IdPage() {
  const ctx = await requireSession();
  const { profile, school } = ctx;

  return (
    <div className="space-y-6 max-w-3xl">
      <div>
        <h1 className="text-2xl font-bold tracking-tight">My SchoolID</h1>
        <p className="text-sm mt-1" style={{ color: 'var(--muted)' }}>
          Your verified digital identity. Show it at the gate, the library, anywhere.
        </p>
      </div>

      <IdCard
        schoolName={school?.name ?? 'SchoolID Platform'}
        schoolMotto={school?.motto}
        primaryColor={school?.primary_color ?? '#4f46e5'}
        personName={profile.people?.full_name ?? 'User'}
        roleLabel={roleMeta(profile.role).label}
        title={profile.title}
        schoolidNumber={profile.schoolid_number ?? '—'}
        qrToken={profile.qr_token ?? ''}
        verificationStatus={profile.verification_status}
        photoUrl={profile.people?.photo_url}
      />

      {profile.verification_status !== 'document_verified' ? (
        <PanelCard title="Upgrade to full verification">
          <p className="text-sm mb-4" style={{ color: 'var(--muted)' }}>
            Verify a government-issued document to earn the highest trust level on your
            SchoolID — it shows on every scan of your card.
          </p>
          <VerifyIdentity
            hasPending={Boolean(profile.idvero_ref)}
            defaultCountry={COUNTRY_CODES[(school?.country ?? '').trim().toLowerCase()] ?? 'NG'}
          />
        </PanelCard>
      ) : null}

      <PanelCard title="How your SchoolID works">
        <ul className="space-y-4">
          <li className="flex gap-3">
            <QrCode size={18} className="mt-0.5 shrink-0" style={{ color: 'var(--brand)' }} />
            <p className="text-sm leading-relaxed" style={{ color: 'var(--muted)' }}>
              <span className="font-semibold" style={{ color: 'var(--text)' }}>Anyone can verify, no one can impersonate.</span>{' '}
              The QR opens a public page showing only your name, photo, role and verification status —
              never your records. Security officers scan it at the gate.
            </p>
          </li>
          <li className="flex gap-3">
            <Fingerprint size={18} className="mt-0.5 shrink-0" style={{ color: 'var(--brand)' }} />
            <p className="text-sm leading-relaxed" style={{ color: 'var(--muted)' }}>
              <span className="font-semibold" style={{ color: 'var(--text)' }}>Your number is yours for life.</span>{' '}
              {profile.schoolid_number} is never reissued. Move schools, graduate, come back as
              a teacher — your identity and history stay with you.
            </p>
          </li>
          <li className="flex gap-3">
            <ArrowRightLeft size={18} className="mt-0.5 shrink-0" style={{ color: 'var(--gold)' }} />
            <p className="text-sm leading-relaxed" style={{ color: 'var(--muted)' }}>
              <span className="font-semibold" style={{ color: 'var(--text)' }}>Built to become your Citizen ID.</span>{' '}
              After graduation your SchoolID can migrate into a lifelong Citizen ID — and{' '}
              <span className="font-semibold" style={{ color: 'var(--text)' }}>only with your explicit consent</span>,
              controlling exactly which information carries over.
            </p>
          </li>
          <li className="flex gap-3">
            <Lock size={18} className="mt-0.5 shrink-0" style={{ color: 'var(--success)' }} />
            <p className="text-sm leading-relaxed" style={{ color: 'var(--muted)' }}>
              <span className="font-semibold" style={{ color: 'var(--text)' }}>If your card leaks, rotate it.</span>{' '}
              The QR token can be regenerated by your school administrator without changing
              your SchoolID number.
            </p>
          </li>
        </ul>
      </PanelCard>
    </div>
  );
}
